def test_langgraph_investigation_execution():
    # Load demo telemetry
    client.post("/api/demos/credential_compromise/load")
    alerts = client.get("/api/alerts?is_demo=true").json()
    assert len(alerts) > 0
    alert_id = alerts[0]["id"]

    # Trigger LangGraph investigation
    inv_resp = client.post("/api/investigations", json={"alert_id": alert_id})
    assert inv_resp.status_code == 200
    inv = inv_resp.json()
    
    assert inv["id"].startswith("INV-")
    assert inv["status"] == "COMPLETED"
    assert inv["progress"] == 100
    assert len(inv["findings"]) > 0
    assert len(inv["mitre_mappings"]) > 0
    assert inv["executive_summary"] is not None

    # Check evidence graph
    graph_resp = client.get(f"/api/evidence/{inv['id']}/graph")
    assert graph_resp.status_code == 200
    graph_data = graph_resp.json()
    assert len(graph_data["nodes"]) > 0
    assert len(graph_data["edges"]) > 0

    # Check response actions
    act_resp = client.get(f"/api/response?investigation_id={inv['id']}")
    assert act_resp.status_code == 200
    actions = act_resp.json()
    assert len(actions) > 0
    
    action_id = actions[0]["id"]
    # Approve action
    appr_resp = client.post(f"/api/response/{action_id}/approve", json={"decided_by": "lead_soc_analyst", "comments": "Authorized simulated containment."})
    assert appr_resp.status_code == 200
    assert appr_resp.json()["status"] == "EXECUTED"

    # Download PDF report
    pdf_resp = client.get(f"/api/reports/{inv['id']}/download")
    assert pdf_resp.status_code == 200
    assert pdf_resp.headers["content-type"] == "application/pdf"
    assert len(pdf_resp.content) > 1000 # Verified real PDF content generated by ReportLab!

